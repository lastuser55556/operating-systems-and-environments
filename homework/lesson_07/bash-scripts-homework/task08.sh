#!/usr/bin/env bash
read -r -p "Первое целое число: " a
read -r -p "Второе целое число: " b
if ! [[ $a =~ ^-?[0-9]+$ && $b =~ ^-?[0-9]+$ ]]; then echo "Нужны целые числа" >&2; exit 1; fi
echo "Сумма: $((a+b))"
echo "Разность: $((a-b))"
echo "Произведение: $((a*b))"
if (( b == 0 )); then echo "Деление на ноль невозможно"; else echo "Частное: $((a/b))"; echo "Остаток: $((a%b))"; fi
